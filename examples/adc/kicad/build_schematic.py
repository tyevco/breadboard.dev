"""Draw examples/adc in KiCad (Phase 1 plan M4, gate M4a; ADR-007 D9).

usage (WSL, KiCad 10.0.8):
    PCB_TOOLS=<prettycoolboards>/tools python3 examples/adc/kicad/build_schematic.py [--out DIR]

The same circuit as examples/adc/board.cir, drawn with wires by the
schematic generator of the prettycoolboards repository (`tools/schgen.py`,
`schplace.py`; the board author's own toolchain, read from PCB_TOOLS and
never modified; the committed files were drawn with prettycoolboards
b14b573 and KiCad 10.0.8, and redrawing gives the same .kicad_sch bytes),
then checked (the wiring rule: every local connection is a drawn wire),
ERC'd (0 errors, 0 warnings) and exported with `kicad-cli`:

    U1.PA4 (DRIVE) -> R1 10k -> ADC_IN -> R2 33k -> GND, C1 470n -> GND
    ADC_IN -> U1.PA1 (adc_in)
    U1.PA5 (ALARM) -> R3 330 -> LED -> D1 (red LED) -> GND
    U1.PA6, U1.PA7: not connected (probed through their bindings)

The four signal nets carry global labels so that their KiCad names are the
board file's node names (ADC_IN, not /ADC board/ADC_IN): that is what makes
the outputs comparable byte for byte with `bb run --netlist board.cir`.
U1's supply pins go to +3V3 and GND power symbols; there are no decoupling
capacitors, because board.cir has none (a capacitor on +3V3 would add an
element to the deck). D1 names its package with the `bb:part` field
(ADR-007 D4 stage 2); U1 resolves by its MPN (stage 3); R1-R3 and C1 by
footprint plus value (stage 5).

Outputs (committed): adc.kicad_pro, adc.kicad_sch (root), adc_board.kicad_sch,
adc.net (the netlist bb.toml imports), erc.rpt is not kept.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.environ.get("PCB_TOOLS", os.path.expanduser("/mnt/c/source/tyevco/prettycoolboards/tools"))
sys.dont_write_bytecode = True  # never write __pycache__ into the toolchain's repository
sys.path.insert(0, TOOLS)

import schgen  # noqa: E402
import symlib  # noqa: E402

PROJECT = "adc"
schgen.set_uuid_namespace("breadboard-examples-adc")

MCU = "MCU_ST_STM32F0:STM32F072RBTx"
SIGNALS = {"PA4": "DRIVE", "PA1": "ADC_IN", "PA5": "ALARM"}


def mcu_pins():
    """Every pin of the STM32F072RBTx symbol: supplies to +3V3/GND, the three
    signals, the rest not connected (PA6 and PA7 included)."""
    pins = {}
    for pin in symlib.get(MCU).pins_for_unit(1):
        name = pin.name
        if name in SIGNALS:
            pins[pin.number] = SIGNALS[name]
        elif name.startswith(("VDD", "VBAT")):
            pins[pin.number] = "+3V3"
        elif name.startswith("VSS"):
            pins[pin.number] = "GND"
        else:
            pins[pin.number] = None
    return pins


def build(d):
    d.sheet("ADC board", "adc_board.kicad_sch", "ADC board")
    d.group("STM32F072 reading back the divider it drives (Breadboard examples/adc)",
            "Same circuit as examples/adc/board.cir. PA4 drives R1 into the RC-filtered divider (R2, C1) on\n"
            "ADC_IN, which PA1 reads (adc_in). PA5 drives the alarm LED D1 through R3. PA6 and PA7 are not\n"
            "connected. No decoupling: board.cir has none, and this drawing must give the same analog deck.",
            anchor="U1")
    d.add("U1", MCU, "STM32F072RBT6", "Package_QFP:LQFP-64_10x10mm_P0.5mm", pins=mcu_pins(),
          fields={"MPN": "STM32F072RBT6", "Manufacturer": "STMicroelectronics"})
    d.add("R1", "Device:R", "10k", "Resistor_SMD:R_0603_1608Metric", pins={"1": "DRIVE", "2": "ADC_IN"})
    d.add("R2", "Device:R", "33k", "Resistor_SMD:R_0603_1608Metric", pins={"1": "ADC_IN", "2": "GND"})
    d.add("C1", "Device:C", "470n", "Capacitor_SMD:C_0603_1608Metric", pins={"1": "ADC_IN", "2": "GND"})
    d.add("R3", "Device:R", "330", "Resistor_SMD:R_0603_1608Metric", pins={"1": "ALARM", "2": "LED"})
    d.add("D1", "Device:LED", "red", "LED_SMD:LED_0603_1608Metric", pins={"2": "LED", "1": "GND"},
          fields={"bb:part": "example/led-red"})
    # The supplies come from outside this drawing (board.cir has no supply
    # either): PWR_FLAGs say so to ERC. They are power symbols, not parts.
    d.add("#FLG01", "power:PWR_FLAG", "PWR_FLAG", pins={"1": "+3V3"})
    d.add("#FLG02", "power:PWR_FLAG", "PWR_FLAG", pins={"1": "GND"})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=HERE)
    args = ap.parse_args()
    d = schgen.Design(PROJECT, "Breadboard examples/adc", "1", "2026-11-09", "Breadboard")
    d.power("+3V3", "GND")
    d.intersheet = {"DRIVE", "ADC_IN", "ALARM", "LED"}
    d.root_notes = ["Generated by examples/adc/kicad/build_schematic.py (Breadboard, Phase 1 M4). Do not hand-edit."]
    build(d)
    errs = d.check()
    for w in d.warnings:
        print("warning:", w)
    if errs:
        for e in errs:
            print("CHECK:", e)
        sys.exit(1)
    d.write(args.out)
    sch = os.path.join(args.out, PROJECT + ".kicad_sch")
    rpt = os.path.join(args.out, "erc.rpt")
    subprocess.run(["kicad-cli", "sch", "erc", "--severity-all", "-o", rpt, sch], capture_output=True, text=True)
    with open(rpt, encoding="utf-8") as f:
        print(f.read())
    os.remove(rpt)
    net = os.path.join(args.out, PROJECT + ".net")
    subprocess.run(["kicad-cli", "sch", "export", "netlist", "--format", "kicadsexpr", "-o", net, sch],
                   check=True, capture_output=True)
    prl = os.path.join(args.out, PROJECT + ".kicad_prl")
    if os.path.exists(prl):
        os.remove(prl)
    print("wrote", sch, net)


if __name__ == "__main__":
    main()
