class _Captured(Exception):
    pass


class Suite:
    """The suite's modules from a `git archive` export, with run() captured."""

    def __init__(self, src: str):
        sim = os.path.join(src, "hardware", "sim")
        sys.path.insert(0, sim)
        sys.path.insert(0, os.path.join(sim, "tests"))
        import spicelib  # noqa: E402
        import test_load_switches as tls  # noqa: E402
        self.spicelib, self.tls = spicelib, tls
        self.real_run = tls.run
        self.stub_dir = tempfile.mkdtemp(prefix="bb-dms-pkg-")
        self.stub = os.path.join(self.stub_dir, STUB_NAME)
        with open(self.stub, "w") as f:
            f.write(STUB)
        self.main = spicelib.Design("main")
        self.base = spicelib.Design("base")

    def capture(self, fn):
        """Run a suite deck builder with U2 replaced by the stub; return the Deck it would have run."""
        got = {}

        def fake_run(deck, need=(), timeout=90):
            got["deck"] = deck
            raise _Captured()

        tls = self.tls
        tls.run, lib = fake_run, tls.LIB_SW
        tls.LIB_SW = self.stub
        try:
            fn()
        except _Captured:
            pass
        finally:
            tls.run, tls.LIB_SW = self.real_run, lib
        self.main.reset()
        return got["deck"]

    def run_real(self, fn):
        """Run a suite deck builder as the suite does (its own view, its own run())."""
        r = fn()
        self.main.reset()
        return r


def _split_instance(line: str, subckt: str):
    """`X<ref> n1 n2 ... <subckt> [params: k=v ...]` -> (ref, nodes, {k: v})."""
    m = re.match(rf"(?i)^X(\S+)\s+(.*?)\s+{subckt}(?:\s+params:\s*(.*))?\s*$", line)
    if not m:
        return None
    params = dict(kv.split("=", 1) for kv in (m.group(3) or "").split())
    return m.group(1), m.group(2).split(), params


def body_from_deck(deck, *, drop_includes=(), drop_sources=(), cut=None, cut_replace=None, extra=()):
    """The deck's circuit lines as a test-circuit body: includes named in drop_includes removed (the stub,
    or the view's own file), sources in drop_sources removed (they become [[edge]] inputs), the instance
    of `cut` = (ref, subckt) removed (it becomes X1) or replaced by `cut_replace` lines; no title, .options,
    analyses or .control (the runner adds them). Returns (body, (nodes, params) of the cut instance)."""
    out, found, seen = [], None, set()
    for chunk in deck.lines:
        if chunk.startswith("* ---- "):
            name = chunk.split("\n", 1)[0][len("* ---- "):].strip()
            # a file the suite includes twice (once per GPIO pad) goes in once: ngspice ignores the second copy
            if name in drop_includes or chunk in seen:
                continue
            seen.add(chunk)
            out.append(chunk.rstrip("\n"))
            continue
        for ln in chunk.splitlines():
            tok = ln.split()
            if tok and tok[0].upper() in {s.upper() for s in drop_sources}:
                continue
            if cut and tok and tok[0].upper() == "X" + cut[0].upper():
                inst = _split_instance(ln, cut[1])
                assert inst is not None, ln
                found = inst[1:]
                if cut_replace:
                    out.extend(cut_replace(inst[1]))
                continue
            out.append(ln)
    if cut:
        assert found is not None, f"instance X{cut[0]} not in the deck"
    out.extend(extra)
    return "\n".join(out) + "\n", found


def write(path: str, text: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def fmt_ms(t_s: float) -> str:
    """A time in s as exact ms text, rounded to 1 ns (every tolerance here is >= 1 us)."""
    ns = round(t_s * 1e9)
    return f"{ns // 1_000_000}.{ns % 1_000_000:06d}ms"


def fmt_v(v: float) -> str:
    uv = round(v * 1e6)
    sign = "-" if uv < 0 else ""
    uv = abs(uv)
    return f"{sign}{uv // 1_000_000}.{uv % 1_000_000:06d}V"


def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def vector_toml(head_comment: str, view: str, circuit: str, stop: str, ports: dict, edges=(), expects=(),
                params=None, sample=None) -> str:
    out = [f"# {ln}" if ln else "#" for ln in head_comment.splitlines()]
    out += ['schema = "bb-pkgtest/0"', f"view = {toml_str(view)}", f"circuit = {toml_str(circuit)}",
            f"stop = {toml_str(stop)}"]
    if sample:
        out.append(f"sample = {toml_str(sample)}")
    if params:
        out.append("params = { " + ", ".join(f"{k} = {toml_str(v)}" for k, v in params.items()) + " }")
    out += ["", "[ports]"]
    for k, v in ports.items():
        out.append(f"{k} = {toml_str(v)}")
    for e in edges:
        out += ["", "[[edge]]", f"net = {toml_str(e['net'])}"]
        if e.get("initial"):
            out.append(f"initial = {toml_str(e['initial'])}")
        m = e["model"]
        out.append("model = { " + ", ".join(f"{k} = {toml_str(m[k])}" for k in ("voh", "vol", "rise", "fall", "zout"))
                   + " }")
        out.append("at = [" + ", ".join(f"[{toml_str(t)}, {toml_str(lv)}]" for t, lv in e["at"]) + "]")
    for x in expects:
        out += ["", "[[expect]]"]
        meas = x["meas"]
        out.append("meas = { " + ", ".join(f"{k} = {toml_str(v)}" for k, v in meas.items()) + " }")
        out += [f"value = {toml_str(x['value'])}", f"tol = {toml_str(x['tol'])}", f"source = {toml_str(x['source'])}"]
    return "\n".join(out) + "\n"


