def ws_cases(s: Suite, ck: Checks):
    """The WS2812C pixel vectors: the suite's phantom operating point (U2 off, P0.06 driven high), with U2
    replaced by its off state (QOD_OFF_OHM from LSW_QOD to GND) and D101 as X1."""
    tls = s.tls
    cases = []
    rj = "examples/dial-me-spinner/suite/results.json (M0, 6854d25)"
    for corner, temp in (("bat4.2", 25), ("usb5.0", 60)):
        test = f"test_phantom_vled_and_din_current[{corner}-{temp}]"
        deck = s.capture(lambda: tls.phantom_op(s.main, s.base, corner, temp))
        n_din = s.main.node("LED_DIN")

        def u2_off(nodes):
            qod, ct, vin = (nodes[TPS_PORTS.index(p)] for p in ("QOD", "CT", "VIN"))
            return [f"* U2 (TPS22917) in its off state: its quick output discharge, {QOD_OFF_OHM} Ohm from QOD to GND",
                    "* (the vendor-derived view's QOD at VIN >= 3.5 V, results.json test_model_ron_qod_and_on_threshold),",
                    "* and CT held at VIN (a disabled TPS22917 resets CT to VIN; otherwise the CT node has no DC path).",
                    "* Its other off-state currents (ISD, the ON pull-down) are nanoamps and are left out.",
                    f"R_U2_QOD_OFF {qod} 0 {QOD_OFF_OHM}",
                    f"R_U2_CT_OFF {ct} {vin} 100"]
        body, _ = body_from_deck(deck, drop_includes=(STUB_NAME,), cut=("U2", "LSW_TPS22917"), cut_replace=u2_off)
        # D101 is X1: cut it from the body (a second pass on the body text).
        lines, d101 = [], None
        for ln in body.splitlines():
            if ln.split()[:1] == ["XD101"]:
                d101 = _split_instance(ln, "LSW_WS2812C")
                continue
            lines.append(ln)
        assert d101 is not None
        # the pixel view's file is the package's own: drop the suite's inlined copy
        text = "\n".join(lines) + "\n"
        text = re.sub(r"(?ms)^\* ---- load_switches__ws2812c\.lib\n.*?^\.ends LSW_WS2812C\n", "", text)
        assert "LSW_WS2812C DIN" not in text
        text += f"BOVER n_din_over 0 V = V({n_din}) - V(n_vled)\n"
        vled = ck(test, f"phantom VLED (P0.06 high, U2 off) {corner} {temp}C")
        idin = ck(test, f"DIN clamp current (record) {corner} {temp}C")
        exp = [dict(meas={"node": "n_vled", "at": "10us"}, value=fmt_v(vled), tol="1mV",
                    src=f"{rj}: {test} phantom VLED")]
        if corner == "bat4.2":
            over = ck(f"test_phantom_din_abs_max[{corner}-{temp}]", f"DIN - VDD with P0.06 high, VLED off {corner} {temp}C")
            exp.append(dict(meas={"node": "n_din_over", "at": "10us"}, value=fmt_v(over), tol="1mV",
                            src=f"{rj}: test_phantom_din_abs_max[{corner}-{temp}] DIN - VDD"))
        cases.append(dict(
            name=f"phantom_{corner}_{temp}", nodes=d101[1], params=d101[2], body=text, stop="10us", test=test,
            comment=(f"WS2812C D101 (X1) and the other 47 pixels on VLED, the firmware fault of the suite's {test}:\n"
                     f"U2 off, P0.06 driven high (nRF52840 high drive, strongest pad), so D101's DIN clamp feeds VLED through\n"
                     f"R40 220 Ohm. U2 stands in as its off-state QOD resistance (the circuit's comment says why). The\n"
                     f"operating point at the first sample is the suite's .op result. DIN clamp current (record): {idin:.6g} A."),
            expects=exp))
    return cases


