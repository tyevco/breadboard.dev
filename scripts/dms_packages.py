def cmd_gpio(a):
    """ADR-006 D9 rule 2 for nordic/nrf52840-qiaa: its named digital_out sets carry the suite's GPIO
    numbers (test_load_switches.py ROUT, 0.4 V / I at the PS columns, to the suite's 6 significant digits,
    and motor_drive's 800 Ohm bound)."""
    import tomllib
    s = Suite(a.src)
    rout = s.tls.ROUT
    want = {"S0S1": rout["sd_typ"], "S0S1_min": rout["sd_min"], "S0S1_max": rout["sd_max"], "default": rout["sd_typ"],
            "H0H1": rout["hd_typ"], "H0H1_min": rout["hd_min"], "H0H1_max": rout["hd_max"], "S0S1_bound": 0.4 / 0.5e-3}
    sets = tomllib.load(open(a.pins, "rb"))["defaults"]["digital_out"]
    bad = []
    for name, r in want.items():
        got = sets[name]["zout"]
        if got != f"{r:.6g}":
            bad.append(f"{name}: zout {got}, the suite's {r:.6g}")
    if set(sets) != set(want):
        bad.append(f"sets {sorted(sets)}, expected {sorted(want)}")
    for b in bad:
        print("dms-packages: GPIO set mismatch:", b)
    print(f"dms-packages: nordic/nrf52840-qiaa digital_out sets {'match' if not bad else 'DO NOT match'} the suite's "
          f"GPIO resistances ({len(want)} sets)")
    sys.exit(1 if bad else 0)


