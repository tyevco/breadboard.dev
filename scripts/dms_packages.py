        test = f"test_model_turn_on_matches_table_7_6[{vin}]"
        deck = s.capture(lambda: tls.test_model_turn_on_matches_table_7_6(None, vin))
        body, (nodes, params) = body_from_deck(deck, drop_includes=(STUB_NAME,), drop_sources=("VON",),
                                               cut=("U", "LSW_TPS22917"))
