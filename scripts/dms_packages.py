class Checks:
    def __init__(self, path: str):
        d = json.load(open(path))
        self.checks = {(c["test"].split("::")[-1], c["check"]): c["value"] for c in d["checks"]}

    def __call__(self, test: str, check: str) -> float:
        return float(self.checks[(test, check)])


