def rename_gnd_port(text: str, subckt: str, new: str = "GNDP") -> str:
    """D9 rule 1: rename the GND port of `subckt` (and its uses inside it) to `new`."""
    out, inside = [], False
    for ln in text.splitlines():
        low = ln.strip().lower()
        if low.startswith(".subckt") and low.split()[1] == subckt.lower():
            inside = True
        if inside and not low.startswith("*"):
            ln = re.sub(r"(?i)(?<![\w.])gnd(?![\w.])", new, ln)
        if inside and low.startswith(".ends"):
            inside = False
        out.append(ln)
    return "\n".join(out) + "\n"


